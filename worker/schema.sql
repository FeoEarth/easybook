CREATE TABLE IF NOT EXISTS notes (
 workspace TEXT NOT NULL, id TEXT NOT NULL, title TEXT NOT NULL, body TEXT NOT NULL,
 icon TEXT NOT NULL, favorite INTEGER NOT NULL DEFAULT 0, deleted INTEGER NOT NULL DEFAULT 0,
 folder_id TEXT NOT NULL DEFAULT '',
 version INTEGER NOT NULL, mutation TEXT NOT NULL, updated INTEGER NOT NULL,
 PRIMARY KEY(workspace, id)
);

CREATE TABLE IF NOT EXISTS folders (workspace TEXT NOT NULL,id TEXT NOT NULL,name TEXT NOT NULL,updated INTEGER NOT NULL,PRIMARY KEY(workspace,id));
