import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
const read=p=>readFileSync(p,'utf8');
const html=read('app/src/main/assets/index.html');
new Script(html.split('<script>')[1].split('</script>')[0]);
const protocol=read('shared/local-ai-protocol.mjs');
const worker=read('worker/ai.mjs');
const oauth=read('mcp-oauth/src/index.mjs');
const manifest=read('app/src/main/AndroidManifest.xml');
const vm=read('app/src/main/java/com/feoearth/easybook/AgentVmBridge.java');
const java=read('app/src/main/java/com/feoearth/easybook/MainActivity.java');
const security=read('app/src/main/java/com/feoearth/easybook/SecurityManager.java');
const runner=read('tools/agent-vm/runner.sh');
const boot=read('tools/agent-vm/start-qemu.sh');
const files=read('app/src/main/assets/agent-sandbox-client.mjs');
assert.match(html,/id="aiSandboxImportInput"/);
assert.match(html,/id="aiSandboxBackend"/);
assert.match(html,/id="aiVmEnabled"/);
assert.match(html,/sandbox\.vm\.execute/);
assert.match(html,/sandbox\.export/);
for(const name of ['listSandboxFiles','importSandboxFiles','getSandboxExport','clearSandboxFiles','removeSandboxFile'])
 assert.ok(files.includes('export async function '+name),name);
for(const layer of [protocol,worker,oauth,security])
 assert.match(layer,/localSandboxBackend|sandboxBackend|sandbox_execute/);
assert.match(manifest,/com\.termux\.permission\.RUN_COMMAND/);
assert.match(manifest,/AgentVmResultReceiver" android:exported="false"/);
assert.match(vm,/RUN_COMMAND_PATH","~\/easybook-agent-vm\/runner\.sh"/);
assert.match(vm,/RUN_COMMAND_PENDING_INTENT/);
assert.match(vm,/checkSelfPermission\(PERMISSION\)/);
assert.match(vm,/PENDING\.isEmpty\(\)/);
assert.match(java,/vmIo\.execute\(operation\)/,'VM calls must not block the standard storage queue');
assert.match(runner,/StrictHostKeyChecking=yes/);
assert.match(runner,/UserKnownHostsFile/);
assert.match(runner,/ClearAllForwardings=yes/);
assert.match(runner,/timeout --signal=TERM/);
assert.doesNotMatch(runner,/eval |sshpass|StrictHostKeyChecking=no|bash -c/);
assert.match(boot,/qemu-system-aarch64/);
assert.match(boot,/hostfwd=tcp:127\.0\.0\.1:2222-:22/);
assert.doesNotMatch(boot,/-virtfs|virtiofs|hostfwd=tcp:0\.0\.0\.0/);
console.log('Agent VM permission, guest routing, isolated file APIs and UI hooks OK');
