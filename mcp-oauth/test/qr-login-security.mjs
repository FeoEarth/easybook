import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {qrLoginRoutes} from '../src/qr-login.mjs';
import {hash} from '../../worker/mcp-common.mjs';
import {random,csrf,session} from '../src/accounts.mjs';
import {s256} from '../src/native-sessions.mjs';

const sqlite=new DatabaseSync(':memory:');
for(const file of ['mcp-oauth/migrations/0002_accounts.sql','mcp-oauth/migrations/0003_passkeys.sql','mcp-oauth/migrations/0004_native_identity.sql','mcp-oauth/migrations/0010_qr_login.sql'])sqlite.exec(readFileSync(file,'utf8'));
const DB={prepare(sql){const query=sqlite.prepare(sql);let params=[];return {bind(...args){params=args;return this},async first(){return query.get(...params)||null},async all(){return {results:query.all(...params)}},async run(){return query.run(...params)}}},async batch(stmts){const out=[];sqlite.exec('BEGIN');try{for(const stmt of stmts)out.push(await stmt.run());sqlite.exec('COMMIT');return out}catch(e){sqlite.exec('ROLLBACK');throw e}}};
const env={DB,IDENTITY_CANONICAL_V2:'true'},base='https://easybook.loonxy.com',user='qr-test-account';
const now=Date.now(),sourceToken=random(),sourceId=crypto.randomUUID();
sqlite.prepare('INSERT INTO accounts(id,display_name,created_at) VALUES(?,?,?)').run(user,'Security tester',now);
sqlite.prepare('INSERT INTO account_sessions(id,token_hash,account_id,created_at,expires_at,authenticated_at,device) VALUES(?,?,?,?,?,?,?)').run(sourceId,await hash(sourceToken),user,now,now+86400000,now,'Test approval');
const originHeaders={'Origin':base,'Content-Type':'application/json'};
const nativeHeaders={'X-Easybook-Native':'1','Content-Type':'application/json'};
const authCookie='__Host-easybook-session='+sourceToken;
const query=(path,opts={})=>qrLoginRoutes(new Request(base+path,opts),env);
const post=(path,data,headers=originHeaders)=>query(path,{method:'POST',headers,body:JSON.stringify(data)});
const result=async response=>({status:response.status,body:await response.json()});
const verifier=random(),state=random(),challenge=await s256(verifier);
const started=await result(await post('/account/native/qr/start',{challenge,state},nativeHeaders));
assert.equal(started.status,200);assert.match(started.body.id,/^[a-f0-9]{64}$/);
assert.match(started.body.confirm_url,/^https:\/\/easybook\.loonxy\.com\/account\/qr\/approve\?id=/);
assert(started.body.qr_rows.length>=21);
assert(started.body.qr_rows.every(row=>row.length===started.body.qr_rows.length));
const id=started.body.id,grant={id,state,verifier};
assert.deepEqual((await result(await post('/account/native/qr/status',grant,nativeHeaders))).body,{status:'pending'});
assert.equal((await post('/account/native/qr/redeem',grant,nativeHeaders)).status,409);
assert.equal((await post('/account/native/qr/status',{id,state,verifier:random()},nativeHeaders)).status,400);
assert.equal((await post('/account/native/qr/approve',{id,decision:'allow'},nativeHeaders)).status,401);
const approvalGet=await query('/account/qr/approve?id='+id,{headers:{Cookie:authCookie}});
assert.equal(approvalGet.status,200);
assert((await approvalGet.text()).includes('确认扫码登录'));
const browserReq=new Request(base+'/account/qr/approve',{headers:{Cookie:authCookie}});
const authenticated=await session(browserReq,env);
const form=new URLSearchParams({id,decision:'allow',csrf:await csrf(browserReq,authenticated)});
assert.equal((await query('/account/qr/approve',{method:'POST',headers:{Origin:'https://attacker.invalid',Cookie:authCookie,'Content-Type':'application/x-www-form-urlencoded'},body:form})).status,403);
const accepted=await query('/account/qr/approve',{method:'POST',headers:{Origin:base,Cookie:authCookie,'Content-Type':'application/x-www-form-urlencoded'},body:form});
assert.equal(accepted.status,200);
assert.equal((await result(await post('/account/native/qr/status',grant,nativeHeaders))).body.status,'approved');
assert.equal((await post('/account/native/qr/redeem',{id,state,verifier:random()},nativeHeaders)).status,400);
const redeemed=await result(await post('/account/native/qr/redeem',grant,nativeHeaders));
assert.equal(redeemed.status,200);assert.match(redeemed.body.token,/^[a-f0-9]{64}$/);
assert.equal((await post('/account/native/qr/redeem',grant,nativeHeaders)).status,400);
assert(sqlite.prepare('SELECT session_id FROM account_native_sessions WHERE session_id=?').get(redeemed.body.session_id));
const webLogin=await query('/account/qr');
assert.equal(webLogin.status,200);
const qrCookie=webLogin.headers.get('set-cookie').split(';')[0];
assert.match(qrCookie,/__Host-easybook-qr-login=/);
const page=await webLogin.text();
const match=page.match(/account\/qr\/approve\?id=([a-f0-9]{64})/);assert(match);
const secondId=match[1];
const secondForm=new URLSearchParams({id:secondId,decision:'allow',csrf:await csrf(browserReq,authenticated)});
assert.equal((await query('/account/qr/approve',{method:'POST',headers:{Origin:base,Cookie:authCookie},body:secondForm})).status,200);
const waiting=await query('/account/qr/wait',{headers:{Cookie:qrCookie}});
assert.equal(waiting.status,303);assert.equal(waiting.headers.get('location'),'/account');
assert(waiting.headers.getSetCookie().some(x=>x.startsWith('__Host-easybook-session=')));
const repeated=await query('/account/qr/wait',{headers:{Cookie:qrCookie}});
assert.equal(repeated.status,303);assert.equal(repeated.headers.get('location'),'/account/qr');
console.log('QR login security integration tests passed');
