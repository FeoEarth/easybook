export function normalizeChatTitle(value){
 if(typeof value!=='string'||/^\s*```/.test(value))return '';
 let title=(value.trim().split(/\r?\n/).find(line=>line.trim())||'')
  .replace(/^\s*(?:标题|Title)\s*[:：]\s*/i,'').replace(/^[#\s]+/,'')
  .replace(/^["'“”‘’`*_]+|["'“”‘’`*_]+$/g,'').replace(/[。！？!?；;：:]+$/,'').replace(/\s+/g,' ').trim();
 if(!title||/[<>\u0000-\u001f]/.test(title)||/^[{\[]/.test(title))return '';
 return Array.from(title).length<=80?title:'';
}

